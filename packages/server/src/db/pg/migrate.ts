/** Error code for "relation does not exist" (never-migrated database). */
const UNDEFINED_TABLE = '42P01';

/**
 * Create every table + index if absent and record the schema version, all in
 * one transaction. Idempotent — running twice is a no-op. Returns the schema
 * version now recorded in `schema_version`.
 */
export async function migratePg(pool: pg.Pool): Promise<number> {
  await withTransaction(pool, async (client) => {
    await client.query(DDL);
    await client.query(
      `INSERT INTO schema_version (id, version) VALUES (1, $1)
       ON CONFLICT (id) DO UPDATE SET version = EXCLUDED.version`,
      [SCHEMA_VERSION],
    );
  });
  return SCHEMA_VERSION;
}

/** Read the recorded schema version (0 if never migrated). */
export async function schemaVersionPg(pool: pg.Pool): Promise<number> {
  try {
    const res = await pool.query<{ version: number }>(
      `SELECT version FROM schema_version WHERE id = 1`,
    );
    return res.rows[0]?.version ?? 0;
  } catch (err) {
    if ((err as { code?: string }).code === UNDEFINED_TABLE) return 0;
    throw err;
  }
}

/** List existing user tables (for tests / diagnostics). */
export async function existingTablesPg(pool: pg.Pool): Promise<string[]> {
  const res = await pool.query<{ tablename: string }>(
    `SELECT tablename FROM pg_tables WHERE schemaname = 'public' ORDER BY tablename`,
  );
  return res.rows.map((r) => r.tablename);
}
