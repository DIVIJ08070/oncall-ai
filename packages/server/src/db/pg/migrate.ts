import type pg from 'pg';
/** Bumped with every DDL change (was shared with the sqlite driver). */
const SCHEMA_VERSION = 2;
import { withTransaction } from './pool.js';

/**
 * Idempotent PostgreSQL schema migration — the full sqlite DDL (SPEC §8)
 * translated, plus the AI Incident PREVENTION tables (Phase 1). All 15 tables
 * + indexes, executed inside **one transaction**.
 *
 * Translation decisions (sqlite → postgres):
 *
 *  - `TEXT` → `TEXT` (ids stay prefixed-ULID strings; no identity change).
 *  - `INTEGER` → `BIGINT` everywhere: ms-epoch timestamps exceed int4 range,
 *    and one uniform integer type keeps the DDL predictable. `pool.ts`
 *    registers an int8 → JS-number parser so row shapes match sqlite exactly.
 *  - `REAL` → `DOUBLE PRECISION` (float8, natively parsed to JS number).
 *  - `INTEGER PRIMARY KEY AUTOINCREMENT` (metric_samples.id) →
 *    `BIGINT GENERATED BY DEFAULT AS IDENTITY` — BY DEFAULT (not ALWAYS) so
 *    tests/replay may still insert explicit ids; inserts use `RETURNING id`.
 *  - Booleans stay `0/1` integers (`deploys.is_current`) so the shared
 *    `boolToInt`/`intToBool` codecs work identically on both drivers.
 *  - The intentional **cyclic FK** (`incidents.pr_id → pull_requests.id` and
 *    `pull_requests.incident_id → incidents.id`): postgres, unlike sqlite,
 *    refuses an inline FK to a not-yet-created table, so `incidents` is
 *    created without it and the constraint is added afterwards via an
 *    idempotent `DO` block once `pull_requests` exists.
 *  - sqlite's `PRAGMA user_version` → a single-row `schema_version` table.
 */

